-- Schema inicial do dominio Attus Imoveis.
--
-- Extraido do banco que o Hibernate construiu com ddl-auto=update ao longo das
-- specs 01 a 11, para que a migracao descreva exatamente o que ja existe. A
-- partir daqui ddl-auto e "validate": o schema pertence a este arquivo, e o
-- mapeamento JPA e conferido contra ele na subida.
--
-- Banco que ja rodou com ddl-auto adota esta versao por baseline, sem recriar
-- nada; banco vazio recebe o schema inteiro por aqui.

CREATE TABLE public.announcement_views (
    id bigint NOT NULL,
    viewed_at timestamp(6) without time zone NOT NULL,
    announcement_id bigint NOT NULL,
    user_id bigint NOT NULL
);

ALTER TABLE public.announcement_views ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.announcement_views_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.announcements (
    id bigint NOT NULL,
    area numeric(38,2) NOT NULL,
    bath_rooms integer NOT NULL,
    cep character varying(9) NOT NULL,
    city character varying(40) NOT NULL,
    complement character varying(60),
    created_at timestamp(6) without time zone NOT NULL,
    description text,
    image character varying(100) NOT NULL,
    price numeric(38,2) NOT NULL,
    property_type character varying(20) NOT NULL,
    reason character varying(20) NOT NULL,
    rooms integer NOT NULL,
    state character varying(20) NOT NULL,
    street character varying(80) NOT NULL,
    street_number integer NOT NULL,
    title character varying(100) NOT NULL,
    updated_at timestamp(6) without time zone,
    user_id bigint NOT NULL,
    CONSTRAINT announcements_property_type_check CHECK (((property_type)::text = ANY ((ARRAY['HOUSE'::character varying, 'APARTMENT'::character varying, 'CONDOMINIUM'::character varying, 'LAND'::character varying])::text[]))),
    CONSTRAINT announcements_reason_check CHECK (((reason)::text = ANY ((ARRAY['SALE'::character varying, 'RENT'::character varying])::text[])))
);

ALTER TABLE public.announcements ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.announcements_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

